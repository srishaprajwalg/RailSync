# Type-specific average speeds (km/min) used for interpolating missing stops.
TYPE_SPEEDS = {
    "Vande Bharat": 1.5,   # ~90 km/h
    "Rajdhani": 1.4,       # ~84 km/h
    "Shatabdi": 1.3,       # ~78 km/h
    "Superfast": 1.1,      # ~66 km/h
    "Express": 0.9,        # ~54 km/h
    "Passenger": 0.6,      # ~36 km/h
}

# Default halt durations (minutes) at intermediate stations, by train type.
TYPE_HALT_MINS = {
    "Vande Bharat": 1,
    "Rajdhani": 1,
    "Shatabdi": 2,
    "Superfast": 2,
    "Express": 3,
    "Passenger": 5,
}

