_cached_stations: Dict[str, List[Station]] = {}
_cached_timetables: Dict[str, List[TrainSchedule]] = {}

def get_corridor_stations(corridor_id: str = "SBC-JTJ") -> List[Station]:
    """Returns the corridor stations with real names and rescaled chainage for the given corridor."""
    if corridor_id not in _cached_stations:
        _cached_stations[corridor_id] = _load_corridor_stations(corridor_id)
    return _cached_stations[corridor_id]

def get_real_timetables(corridor_id: str = "SBC-JTJ") -> List[TrainSchedule]:
    """Returns real train schedules across the planning horizon for the given corridor."""
    if corridor_id in _cached_timetables:
        return _cached_timetables[corridor_id]

    cfg = CORRIDOR_CONFIGS.get(corridor_id, CORRIDOR_CONFIGS["SBC-JTJ"])
    target_count = cfg.get("target_trains_per_dir", 15)
    shatabdi_pair = cfg.get("shatabdi_pair", ("12028", "12027"))

    stations = get_corridor_stations(corridor_id)
    chainage_map = {s.code: s.chainage_km for s in stations}

    candidate_trains = _load_corridor_schedules(corridor_id)
    up_candidates = [t for t in candidate_trains if t["direction"] == "Up"]
    dn_candidates = [t for t in candidate_trains if t["direction"] == "Down"]

    def _select_trains(candidates, direction):
        selected = []
        shatabdi_added = False
        sorted_cand = sorted(candidates, key=lambda x: (x["stops_count"], x["span"]), reverse=True)

        target_shatabdi = shatabdi_pair[0] if direction == "Up" else shatabdi_pair[1]
        for c in sorted_cand:
            if c["train_number"] == target_shatabdi and c["type"] in ("Shatabdi", "Superfast"):
                selected.append(c)
                shatabdi_added = True
                break

        if not shatabdi_added:
            for c in sorted_cand:
                if c["type"] == "Shatabdi":
                    selected.append(c)
                    shatabdi_added = True
                    break

        pass_count = 0
        for c in sorted_cand:
            if c["type"] == "Passenger" and c not in selected and pass_count < 3:
                selected.append(c)
                pass_count += 1

        for c in sorted_cand:
            if len(selected) >= target_count:
                break
            if c["type"] == "Shatabdi":
                continue
            if c not in selected:
                selected.append(c)

        return selected

    selected_up = _select_trains(up_candidates, "Up")
    selected_dn = _select_trains(dn_candidates, "Down")

    day0_schedules: List[Tuple[TrainSchedule, bool]] = []
    for train_meta in selected_up:
        sched = _build_train_schedule(
            train_meta["train_number"],
            train_meta["train_name"],
            train_meta["type"],
            train_meta["rows"],
            stations,
            chainage_map,
            "Up",
        )
        if sched:
            day0_schedules.append((sched, train_meta["type"] == "Shatabdi"))

    for train_meta in selected_dn:
        sched = _build_train_schedule(
            train_meta["train_number"],
            train_meta["train_name"],
            train_meta["type"],
            train_meta["rows"],
            stations,
            chainage_map,
            "Down",
        )
        if sched:
            day0_schedules.append((sched, train_meta["type"] == "Shatabdi"))

    timetables = []
    for day in range(HORIZON_DAYS):
        day_offset = day * MINS_PER_DAY
        for sched, is_shatabdi in day0_schedules:
            if is_shatabdi and day == 2 and corridor_id == "SBC-JTJ":
                continue

            day_stops = [
                TrainStop(
                    station_id=stop.station_id,
                    arrival_mins=stop.arrival_mins + day_offset,
                    departure_mins=stop.departure_mins + day_offset,
                )
                for stop in sched.stops
            ]
            timetables.append(TrainSchedule(
                train_id=f"{sched.train_id}_D{day}",
                type=sched.type,
                direction=sched.direction,
                stops=day_stops,
            ))

    _cached_timetables[corridor_id] = timetables
    return timetables

